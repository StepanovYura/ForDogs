// Способы оплаты — названия и подсказки, общие для оформления заказа,
// страницы заказа, писем и админки.
//
// sbp     — QR-код СБП на нашей странице заказа;
// card    — банковская карта на платёжной странице банка;
// dolyame — «Долями» (сервис Т-Банка): 4 платежа по 25% раз в две недели,
//           оформляется тоже на платёжной странице банка.
// Данные карт (и любые данные для «Долями») вводятся только у банка.

export const METHOD_LABELS = {
  sbp: 'СБП',
  card: 'Карта',
  dolyame: 'Долями',
}

// Как способ называется в письме администратору: «Оплачен …».
export const METHOD_PAID_WITH = {
  sbp: 'по СБП',
  card: 'картой',
  dolyame: 'через «Долями»',
}

// Способы, при которых покупатель платит на странице банка, а не по
// QR-коду на нашем сайте.
export const HOSTED_METHODS = ['card', 'dolyame']

// «Долями»: первый из четырёх платежей. Округляем вверх до копейки —
// банк сам распределит остаток по платежам.
export function dolyamePart(totalKopeks) {
  return Math.ceil(totalKopeks / 4)
}
